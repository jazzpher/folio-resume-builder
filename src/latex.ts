import { blocks, type Resume } from './model';
export const escapeTex = (s: string) =>
  s
    .replace(
      /[\\{}$&%#_^~]/g,
      (c) =>
        ({
          '\\': '\\textbackslash{}',
          '{': '\\{',
          '}': '\\}',
          $: '\\$',
          '&': '\\&',
          '%': '\\%',
          '#': '\\#',
          _: '\\_',
          '^': '\\textasciicircum{}',
          '~': '\\textasciitilde{}',
        })[c]!,
    )
    .replace(/\r?\n/g, ' ');
export function makeTex(r: Resume) {
  return `% Generated by Folio. Compile with pdfLaTeX (e.g. in Overleaf).\n% Single-column, text-based resume. Review content and pagination before applying.\n\\documentclass[11pt,${r.paper === 'A4' ? 'a4paper' : 'letterpaper'}]{article}\n\\usepackage[margin=0.7in]{geometry}\n\\usepackage[T1]{fontenc}\n\\usepackage[utf8]{inputenc}\n\\usepackage{lmodern}\n\\renewcommand{\\familydefault}{\\sfdefault}\n\\pagestyle{empty}\n\\setlength{\\parindent}{0pt}\n\\setlength{\\parskip}{5pt}\n\\begin{document}\n${blocks(
    r,
  )
    .map((b) => {
      const t = escapeTex(b.text);
      switch (b.kind) {
        case 'name':
          return `{\\LARGE\\bfseries ${t}}\\par`;
        case 'heading':
          return `\\par\\medskip{\\large\\bfseries ${t}}\\par\\nopagebreak`;
        case 'role':
          return `\\textbf{${t}}\\par\\nopagebreak`;
        case 'bullet':
          return `{\\setlength{\\parskip}{0pt}\n\\begin{itemize}\n\\setlength{\\itemsep}{0pt}\n\\setlength{\\topsep}{0pt}\n\\item ${t}\n\\end{itemize}}`;
        default:
          return `${t}\\par`;
      }
    })
    .join('\n')}\n\\end{document}\n`;
}
